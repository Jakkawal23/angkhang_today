function merge(base, upd) {
  if (!upd) return base;
  const out = { ...base, ...upd };
  out.sources = [...(base.sources ?? []), ...(upd.sources ?? [])];
  out.highlights = [...(base.highlights ?? []), ...(upd.highlights ?? [])];
  out.amenities = [...new Set([...(base.amenities ?? []), ...(upd.amenities ?? [])])];
  out.location = { ...(base.location ?? {}), ...(upd.location ?? {}) };
  if (upd.contacts) {
    out.contacts = { ...(base.contacts ?? {}), ...upd.contacts, phones: [...(base.contacts?.phones ?? []), ...(upd.contacts.phones ?? [])] };
  }
  return out;
}

